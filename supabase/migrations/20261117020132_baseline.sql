-- =====================================================================
-- 0001 baseline: 원본 팀 프로젝트 DB 스키마 복원
-- =====================================================================
-- 원본 Supabase 프로젝트는 소멸했고 스키마 파일이 남아 있지 않았다.
-- 프론트엔드 코드가 각 테이블에서 읽고 쓰는 컬럼, 필터, 조인, upsert 충돌 키를
-- 역분석해서 "원본 코드가 수정 없이 동작하는 수준"으로 복원한다.
--
-- ⚠️ 의도적으로 원본의 설계를 그대로 재현한다 (고치기 전 상태 = Before 증거용).
--   - RLS(행 단위 보안)를 켜지 않는다. 누구나 모든 행을 읽고 쓸 수 있다.
--   - 브랜드는 FK 없이 '이름 문자열'로 연결된다 (products.brand, orders.items[].brand 등).
--   - 주문 상품은 별도 테이블 없이 orders.items(jsonb)에 들어간다.
--   - 재고 차감은 클라이언트가 조회 -> 계산 -> UPDATE 한다.
--   이 문제들은 이후 마이그레이션(0002~)에서 하나씩 고친다. 설계서 P1~P13 참고.
--
-- 복원 대상에서 제외한 것 (코드 분석 결과 실제로 호출되지 않음)
--   - notices: 관리자 Notice.js의 주석(구현 가이드) 안에서만 등장
--   - categories_level1~3: productService.ts의 옛 함수에서만 사용. 화면은 categoryService.ts의
--     단일 categories(level, parent_id) 테이블을 사용
--   - get_hq_dashboard_stats, get_tables RPC: 호출부에 RPC 실패 시 대체 쿼리가 있거나 호출부가 삭제됨
-- =====================================================================


-- ---------------------------------------------------------------------
-- 회원 (Supabase Auth의 auth.users와 1:1, 가입 직후 클라이언트가 직접 insert)
-- ---------------------------------------------------------------------
create table public.users (
  id               uuid primary key references auth.users (id) on delete cascade,
  email            text not null,
  name             text not null,
  phone            text,
  address          text,
  agree_marketing  boolean not null default false,
  grade            text not null default 'FAMILY',   -- FAMILY / SILVER / GOLD / DIAMOND / PRESTIGE VIP (배송비 무료 판단)
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 카테고리: 한 테이블에 3단계 계층 (level 1~3, parent_id로 상위 연결)
-- ---------------------------------------------------------------------
create table public.categories (
  id           bigint generated by default as identity primary key,
  name         text not null,
  description  text,
  image_url    text,
  level        smallint not null check (level between 1 and 3),
  parent_id    bigint references public.categories (id) on delete cascade,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index categories_parent_id_idx on public.categories (parent_id);
create index categories_level_idx on public.categories (level);


-- ---------------------------------------------------------------------
-- 상품
--   - id: 관리자 화면이 get_next_product_id()로 다음 번호를 받아 직접 지정해서 insert 한다
--   - brand: 브랜드 테이블 FK가 아니라 브랜드 '이름' 문자열
--   - status: 고객 화면은 'forsale'만 노출. 관리자 화면에서 soldout / hidden / pending 등 사용
-- ---------------------------------------------------------------------
create table public.products (
  id           bigint generated by default as identity primary key,
  name         text not null,
  description  text,
  price        integer not null default 0 check (price >= 0),
  brand        text,
  category_id  bigint references public.categories (id) on delete set null,
  status       text not null default 'forsale',
  stock        integer not null default 0,
  sales        integer not null default 0,
  image_urls   text[] not null default '{}',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index products_category_id_idx on public.products (category_id);
create index products_status_idx on public.products (status);
create index products_brand_idx on public.products (brand);


-- ---------------------------------------------------------------------
-- 주문
--   - items: 주문 상품 배열(jsonb). [{product_id, name, price, quantity, image, size, color, brand}]
--   - status: 한글 상태값 (주문접수, 결제완료, 상품준비, 배송중, 배송완료, 주문취소, 반품신청, 반품완료)
--   - user_id FK: 관리자 화면이 orders -> users(name) 조인을 사용
-- ---------------------------------------------------------------------
create table public.orders (
  id                  text primary key default gen_random_uuid()::text,
  user_id             uuid references public.users (id) on delete set null,
  order_date          timestamptz not null default now(),
  status              text not null default '결제완료',
  total_amount        integer not null default 0,
  payment_method      text,
  payment_key         text,
  items               jsonb not null default '[]'::jsonb,
  shipping_address    text,
  recipient_name      text,
  recipient_phone     text,
  tracking_number     text,
  estimated_delivery  text,
  cancel_reason       text,
  return_reason       text,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index orders_user_id_idx on public.orders (user_id);
create index orders_created_at_idx on public.orders (created_at);


-- ---------------------------------------------------------------------
-- 장바구니 (로그인 회원)
--   - 클라이언트가 upsert(onConflict: user_id,product_id,size,color) 사용
--   - 사이즈/색상이 없는 상품은 null로 저장하므로 NULLS NOT DISTINCT로 같은 상품을 한 행으로 취급
-- ---------------------------------------------------------------------
create table public.user_carts (
  id           bigint generated by default as identity primary key,
  user_id      uuid not null references public.users (id) on delete cascade,
  product_id   bigint not null references public.products (id) on delete cascade,
  size         text,
  color        text,
  quantity     integer not null default 1 check (quantity > 0),
  is_selected  boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint user_carts_item_key unique nulls not distinct (user_id, product_id, size, color)
);


-- ---------------------------------------------------------------------
-- 찜, 최근 본 상품 (recent_views -> products(*) 조인 사용)
-- ---------------------------------------------------------------------
create table public.wishlists (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.users (id) on delete cascade,
  product_id  bigint not null references public.products (id) on delete cascade,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint wishlists_user_product_key unique (user_id, product_id)
);

create table public.recent_views (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null references public.users (id) on delete cascade,
  product_id  bigint not null references public.products (id) on delete cascade,
  viewed_at   timestamptz not null default now(),
  constraint recent_views_user_product_key unique (user_id, product_id)
);


-- ---------------------------------------------------------------------
