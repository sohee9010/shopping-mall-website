grant usage on schema public to anon, authenticated;
grant all on all tables in schema public to anon, authenticated;
grant all on all sequences in schema public to anon, authenticated;
grant execute on all functions in schema public to anon, authenticated;


-- =====================================================================
-- Storage 버킷 (공개 읽기) + 업로드 권한
-- =====================================================================
insert into storage.buckets (id, name, public)
values
  ('product-images', 'product-images', true),
  ('brand-logos', 'brand-logos', true)
on conflict (id) do nothing;

-- 원본 재현: 로그인한 사용자는 누구나 두 버킷에 업로드·수정·삭제 가능 (입점사별 구분 없음)
create policy "baseline: authenticated can upload"
  on storage.objects for insert to authenticated
  with check (bucket_id in ('product-images', 'brand-logos'));

create policy "baseline: authenticated can update"
  on storage.objects for update to authenticated
  using (bucket_id in ('product-images', 'brand-logos'));

create policy "baseline: authenticated can delete"
  on storage.objects for delete to authenticated
  using (bucket_id in ('product-images', 'brand-logos'));
