-- =====================================================================
-- RPC (프론트에서 supabase.rpc()로 호출하는 DB 함수)
-- =====================================================================

-- 카테고리와 그 모든 하위 카테고리 id (카테고리 페이지에서 하위 카테고리 상품까지 조회할 때 사용)
create or replace function public.get_all_subcategory_ids(parent_id bigint)
returns setof bigint
language sql
stable
as $$
  with recursive tree as (
    select c.id from public.categories c where c.id = get_all_subcategory_ids.parent_id
    union all
    select c.id from public.categories c join tree t on c.parent_id = t.id
  )
  select id from tree;
$$;

-- 다음 상품 번호 (원본 동작 재현: max(id) + 1)
-- ⚠️ 두 입점사가 동시에 상품을 등록하면 같은 번호를 받아 한쪽이 실패한다(P13). 이후 identity 기본값으로 대체 예정
create or replace function public.get_next_product_id()
returns bigint
language sql
volatile
as $$
  select coalesce(max(id), 0) + 1 from public.products;
$$;


