-- =====================================================================
-- 0007 상품 옵션(SKU) 재설계 — 단계 A
-- =====================================================================
-- 해결하는 문제 (P17: 옵션 기능이 실제로 동작하지 않음)
--   - 상품 상세: 모든 상품에 같은 옵션 버튼이 코드에 고정 (향수에도 XS~XL)
--   - 장바구니: 고른 옵션이 전달되지 않음 / 주문: 장바구니 경유 시 '블랙 / FREE' 고정 저장
--   - 재고가 상품 단위 숫자 하나 → "블랙 M만 품절" 표현 불가
--
-- 설계 (설계서 2-4, ADR: option1/option2 컬럼 방식)
--   - 재고의 단일 진실 원천은 product_variants(SKU). 장바구니·주문·재고 차감은 모두 SKU 기준
--   - 옵션이 없는 상품도 기본 SKU 1개를 가진다 → 주문 로직 분기 없음
--   - 옵션 축은 최대 2개(option1, option2). 축 이름은 product_options에, 값은 SKU에 저장
--   - products.stock / status 는 SKU 재고 합계로 트리거가 맞추는 '목록 표시용 캐시'
--   - place_order 입력(jsonb 배열)의 원소에 variant_id를 추가. 함수 시그니처는 유지
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. 테이블
-- ---------------------------------------------------------------------
create table public.product_options (
  product_id  bigint not null references public.products (id) on delete cascade,
  position    smallint not null check (position in (1, 2)),
  name        text not null,                         -- 예: 색상, 사이즈, 용량, 호수
  primary key (product_id, position)
);

create table public.product_variants (
  id           bigint generated by default as identity primary key,
  product_id   bigint not null references public.products (id) on delete cascade,
  sku          text not null unique,                 -- 재고 관리 코드 (예: LUN-COAT01-BLK-M)
  option1      text,                                 -- product_options.position = 1 의 값 (예: 블랙)
  option2      text,                                 -- product_options.position = 2 의 값 (예: M)
  price_delta  integer not null default 0 check (price_delta >= 0),  -- 옵션 추가금 (예: XL +10,000)
  stock        integer not null default 0 check (stock >= 0),
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  -- 같은 상품에 같은 옵션 조합은 하나만 (옵션 없는 기본 SKU는 null/null)
  constraint product_variants_options_key unique nulls not distinct (product_id, option1, option2),
  -- 2번 옵션만 있고 1번 옵션이 없는 SKU는 만들 수 없다
  constraint product_variants_option_order check (option2 is null or option1 is not null)
);

create index product_variants_product_id_idx on public.product_variants (product_id);

grant select, insert, update, delete on public.product_options, public.product_variants to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;


-- ---------------------------------------------------------------------
-- 2. 기존 상품마다 기본 SKU 생성 (재고 = 기존 products.stock) — 어떤 환경에서도 안전한 이전
-- ---------------------------------------------------------------------
insert into public.product_variants (product_id, sku, stock)
select p.id, 'P' || lpad(p.id::text, 6, '0'), greatest(p.stock, 0)
from public.products p
where not exists (select 1 from public.product_variants v where v.product_id = p.id);


-- ---------------------------------------------------------------------
-- 3. 재고 동기화 트리거
-- ---------------------------------------------------------------------
-- (a) SKU 재고·활성 상태가 바뀌면 상품의 재고 합계와 판매 상태를 맞춘다
create or replace function private.sync_product_stock()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_product_id bigint := coalesce(new.product_id, old.product_id);
  v_total      integer;
begin
  select coalesce(sum(v.stock) filter (where v.is_active), 0) into v_total
    from public.product_variants v where v.product_id = v_product_id;

  update public.products p
     set stock      = v_total,
         -- 판매중/품절 상품만 자동 전환. 검수대기·숨김 등은 관리자가 정한 상태를 유지
         status     = case when p.status in ('forsale', 'soldout')
                           then case when v_total > 0 then 'forsale' else 'soldout' end
                           else p.status end,
         updated_at = now()
   where p.id = v_product_id;
  return null;
end;
$$;

create trigger product_variants_sync_stock
  after insert or delete or update of stock, is_active on public.product_variants
  for each row execute function private.sync_product_stock();

-- (b) 새 상품에는 기본 SKU를 자동으로 만든다 (관리자 화면은 아직 옵션 입력이 없으므로)
create or replace function private.create_default_variant()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.product_variants (product_id, sku, stock)
  values (new.id, 'P' || lpad(new.id::text, 6, '0'), greatest(new.stock, 0));
  return null;
end;
$$;

create trigger products_create_default_variant
  after insert on public.products
  for each row execute function private.create_default_variant();

-- (c) 관리자 화면이 products.stock을 직접 수정한 경우: 옵션 없는 상품(기본 SKU 1개)이면 SKU에 반영
--     옵션이 여러 개인 상품은 SKU별로 수정해야 하므로 반영하지 않는다(다음 동기화 때 합계로 되돌아감)
--     pg_trigger_depth() > 1 : (a)가 맞춘 값으로 다시 들어온 경우 → 무한 반복 방지
create or replace function private.propagate_product_stock()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if pg_trigger_depth() > 1 then
    return null;
  end if;
  update public.product_variants v
     set stock = greatest(new.stock, 0), updated_at = now()
   where v.product_id = new.id
     and v.option1 is null and v.option2 is null
     and (select count(*) from public.product_variants x where x.product_id = new.id) = 1;
  return null;
end;
$$;

create trigger products_propagate_stock
  after update of stock on public.products
  for each row when (old.stock is distinct from new.stock)
  execute function private.propagate_product_stock();


