-- 4. RLS
-- ---------------------------------------------------------------------
alter table public.product_options  enable row level security;
alter table public.product_variants enable row level security;

create policy "product_options: 공개 상품의 옵션 조회" on public.product_options
  for select to anon, authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.status in ('forsale', 'soldout')));
create policy "product_options: 입점사는 자기 브랜드" on public.product_options
  for all to authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.brand = (select private.my_brand_name())))
  with check (exists (select 1 from public.products p where p.id = product_id and p.brand = (select private.my_brand_name())));
create policy "product_options: 본사 관리" on public.product_options
  for all to authenticated using ((select private.is_hq())) with check ((select private.is_hq()));

create policy "product_variants: 공개 상품의 SKU 조회" on public.product_variants
  for select to anon, authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.status in ('forsale', 'soldout')));
create policy "product_variants: 입점사는 자기 브랜드" on public.product_variants
  for all to authenticated
  using (exists (select 1 from public.products p where p.id = product_id and p.brand = (select private.my_brand_name())))
  with check (exists (select 1 from public.products p where p.id = product_id and p.brand = (select private.my_brand_name())));
create policy "product_variants: 본사 관리" on public.product_variants
  for all to authenticated using ((select private.is_hq())) with check ((select private.is_hq()));


