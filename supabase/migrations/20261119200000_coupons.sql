-- =====================================================================
-- 쿠폰 DB화 (P4 쿠폰 부분)
-- =====================================================================
-- 문제
--   쿠폰이 브라우저 localStorage에만 있었다. 개발자 도구로 금액·사용 여부를 고칠 수 있어 서버가 믿을 수 없고,
--   그래서 결제 금액에는 반영하지 못한 채 '쿠폰 할인은 반영되지 않습니다' 안내만 띄우고 있었다.
--
-- 해결
--   1. coupons(정책) / user_coupons(발급) 분리. 고객은 자기 발급 쿠폰을 '조회'만 할 수 있다 (쓰기 정책 없음)
--   2. 할인 금액 계산과 '사용 처리'는 place_order 트랜잭션 안에서만 한다
--      - 발급 쿠폰 행을 잠그고(for update) 미사용·기간·최소 금액을 확인 → 같은 쿠폰으로 동시에 주문해도 한 건만 성공
--      - 할인 후 금액이 orders.total_amount가 되므로, 결제 승인(confirm-payment)·환불은 기존 코드 그대로 할인 금액 기준
--   3. 주문이 결제실패·결제취소·주문취소가 되면 쿠폰을 되돌린다 (재고 복구와 같은 시점)
--   4. 가입 시 자동 발급(issue_on_signup) 쿠폰을 트리거로 발급하고, 기존 회원에게도 한 번 발급한다
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. 테이블
-- ---------------------------------------------------------------------
create table public.coupons (
  id                bigint generated by default as identity primary key,
  name              text not null,
  description       text not null default '',
  discount_type     text not null check (discount_type in ('FIXED', 'PERCENT')),
  discount_value    integer not null check (discount_value > 0),
  min_order_amount  integer not null default 0 check (min_order_amount >= 0),
  max_discount      integer check (max_discount > 0),        -- PERCENT 쿠폰의 최대 할인 금액
  valid_days        integer not null default 30 check (valid_days > 0), -- 발급일로부터 사용 가능 기간
  issue_on_signup   boolean not null default false,
  is_active         boolean not null default true,
  created_at        timestamptz not null default now(),
  check (discount_type <> 'PERCENT' or discount_value <= 100)
);
comment on table public.coupons is '쿠폰 정책 (할인 방식·조건). 고객에게 준 쿠폰은 user_coupons';

create table public.user_coupons (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references public.users (id) on delete cascade,
  coupon_id   bigint not null references public.coupons (id) on delete restrict,
  issued_at   timestamptz not null default now(),
  expires_at  timestamptz not null,
  used_at     timestamptz,
  order_id    text references public.orders (id) on delete set null,
  unique (user_id, coupon_id),                                   -- 같은 쿠폰은 회원당 한 장
  check ((used_at is null) = (order_id is null))                 -- 사용했다면 반드시 어떤 주문에 썼는지 남긴다
);
comment on table public.user_coupons is '회원에게 발급된 쿠폰. 사용 처리는 place_order에서만';
create index user_coupons_user_id_idx on public.user_coupons (user_id);
create index user_coupons_order_id_idx on public.user_coupons (order_id);

-- 주문에 적용된 할인 금액 (표시용. 결제 금액은 total_amount = 상품 합계 + 배송비 - 할인)
alter table public.orders add column discount_amount integer not null default 0 check (discount_amount >= 0);


-- ---------------------------------------------------------------------
-- 2. 권한 (RLS): 고객은 조회만. 발급·사용·복구는 서버 함수와 트리거만
-- ---------------------------------------------------------------------
alter table public.coupons enable row level security;
alter table public.user_coupons enable row level security;

create policy "coupons: 로그인 사용자 조회" on public.coupons
  for select to authenticated using (true);
create policy "coupons: 본사 관리" on public.coupons
  for all to authenticated using ((select private.is_hq())) with check ((select private.is_hq()));

create policy "user_coupons: 본인 쿠폰 조회" on public.user_coupons
  for select to authenticated using (user_id = (select auth.uid()));
create policy "user_coupons: 본사 조회" on public.user_coupons
  for select to authenticated using ((select private.is_hq()));

-- 고객이 orders를 수정할 수 있는 경우(취소 요청 등)에도 할인 금액은 바꾸지 못하게 한다
create or replace function private.guard_order_discount()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.discount_amount is distinct from old.discount_amount
     and coalesce(auth.jwt() ->> 'role', '') <> 'service_role'
     and auth.uid() is not null then
    raise exception '할인 금액은 변경할 수 없습니다' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger orders_guard_discount
  before update of discount_amount on public.orders
  for each row execute function private.guard_order_discount();


-- ---------------------------------------------------------------------
-- 3. 할인 금액 계산 (한 곳에서만 계산: 주문 함수가 사용)
--    FIXED: 할인액, PERCENT: 상품 합계 × 비율(원 단위 내림, 최대 할인 제한). 상품 합계를 넘지 않는다
-- ---------------------------------------------------------------------
create or replace function private.coupon_discount(p_coupon public.coupons, p_subtotal integer)
returns integer
language sql immutable set search_path = ''
as $$
  select least(
    p_subtotal,
    case p_coupon.discount_type
      when 'FIXED'   then p_coupon.discount_value
      when 'PERCENT' then least(
                            (p_subtotal::bigint * p_coupon.discount_value / 100)::integer,
                            coalesce(p_coupon.max_discount, 2147483647))
    end
  );
$$;


-- ---------------------------------------------------------------------
-- 4. 주문 생성: 쿠폰 인자 추가 (0009 place_order_impl + 쿠폰 검증·할인·사용 처리)
-- ---------------------------------------------------------------------
drop function public.place_order(jsonb, text, text, text, text);
drop function private.place_order_impl(jsonb, text, text, text, text);

create or replace function private.place_order_impl(
  p_items             jsonb,
  p_shipping_address  text,
  p_recipient_name    text,
  p_recipient_phone   text,
  p_payment_method    text,
  p_user_coupon_id    bigint
)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id      uuid := auth.uid();
  v_item         jsonb;
  v_quantity     integer;
  v_variant_id   bigint;
  v_variant      public.product_variants;
  v_product      public.products;
  v_option_text  text;
  v_unit_price   integer;
  v_order_items  jsonb := '[]'::jsonb;
  v_subtotal     integer := 0;
  v_shipping_fee integer;
  v_grade        text;
  v_user_coupon  public.user_coupons;
  v_coupon       public.coupons;
  v_discount     integer := 0;
  v_order        public.orders;
begin
  if v_user_id is null then
    raise exception '로그인이 필요합니다' using errcode = '28000';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception '주문할 상품이 없습니다' using errcode = '22023';
  end if;

  -- 상품 id → SKU id 순서로 처리해 동시 주문 간 잠금 순서를 일정하게 (교착 상태 방지)
  for v_item in
    select e.value
      from jsonb_array_elements(p_items) e
      left join public.product_variants pv on pv.id = (e.value ->> 'variant_id')::bigint
     order by coalesce(pv.product_id, (e.value ->> 'product_id')::bigint), pv.id
  loop
    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity is null or v_quantity <= 0 or v_quantity > 99 then
      raise exception '주문 수량이 올바르지 않습니다' using errcode = '22023';
    end if;

    v_variant_id := (v_item ->> 'variant_id')::bigint;
    if v_variant_id is null then
      select v.id into v_variant_id
        from public.product_variants v
       where v.product_id = (v_item ->> 'product_id')::bigint
         and (select count(*) from public.product_variants x where x.product_id = v.product_id) = 1;
      if v_variant_id is null then
        raise exception '옵션을 선택해 주세요 (상품 id=%)', v_item ->> 'product_id'
          using errcode = '22023', hint = 'OPTION_REQUIRED';
      end if;
    end if;

    -- SKU 재고가 충분하고, SKU가 활성이며, 상품이 판매중일 때만 차감 (조건부 UPDATE 한 문장 = 원자적)
    update public.product_variants v
       set stock = v.stock - v_quantity, updated_at = now()
      from public.products p
     where v.id = v_variant_id
       and p.id = v.product_id
       and p.status = 'forsale'
       and v.is_active
       and v.stock >= v_quantity
    returning v.* into v_variant;

    if not found then
      select * into v_variant from public.product_variants v where v.id = v_variant_id;
      if v_variant.id is null then
        raise exception '존재하지 않는 상품 옵션입니다 (id=%)', v_variant_id using errcode = 'P0002';
      end if;
      select * into v_product from public.products p where p.id = v_variant.product_id;
      raise exception '재고가 부족합니다: % % (남은 수량 %개)',
        v_product.name, coalesce('(' || concat_ws(' / ', v_variant.option1, v_variant.option2) || ')', ''),
        case when v_variant.is_active then v_variant.stock else 0 end
        using errcode = 'P0001', hint = 'OUT_OF_STOCK';
    end if;

    update public.products p set sales = p.sales + v_quantity where p.id = v_variant.product_id
    returning p.* into v_product;

    v_option_text := nullif(concat_ws(' / ', v_variant.option1, v_variant.option2), '');
    v_unit_price  := v_product.price + v_variant.price_delta;

    v_order_items := v_order_items || jsonb_build_object(
      'product_id',  v_product.id,
      'variant_id',  v_variant.id,
      'sku',         v_variant.sku,
      'name',        v_product.name,
      'brand',       v_product.brand,
      'option_text', v_option_text,
      'price',       v_unit_price,
      'quantity',    v_quantity,
      'image',       coalesce(v_product.image_urls[1], '')
    );
    v_subtotal := v_subtotal + v_unit_price * v_quantity;
  end loop;

  select u.grade into v_grade from public.users u where u.id = v_user_id;
  v_shipping_fee := case when v_grade in ('SILVER', 'GOLD', 'DIAMOND', 'PRESTIGE VIP') then 0 else 3000 end;

  -- 쿠폰: 본인 쿠폰 행을 잠근 뒤 검사한다. 같은 쿠폰으로 동시에 주문하면 나중 요청은 잠금을 기다렸다가
  -- 이미 사용된 것을 보고 실패한다 (브라우저가 보낸 할인 금액은 받지 않는다. 서버가 계산)
  if p_user_coupon_id is not null then
    select * into v_user_coupon
      from public.user_coupons uc
     where uc.id = p_user_coupon_id and uc.user_id = v_user_id
       for update;
    if not found then
      raise exception '사용할 수 없는 쿠폰입니다' using errcode = 'P0002', hint = 'COUPON_INVALID';
    end if;
    if v_user_coupon.used_at is not null then
      raise exception '이미 사용한 쿠폰입니다' using errcode = 'P0001', hint = 'COUPON_USED';
    end if;
    if v_user_coupon.expires_at < now() then
      raise exception '사용 기간이 지난 쿠폰입니다' using errcode = 'P0001', hint = 'COUPON_EXPIRED';
    end if;
    select * into v_coupon from public.coupons c where c.id = v_user_coupon.coupon_id;
    if not v_coupon.is_active then
      raise exception '사용이 중지된 쿠폰입니다' using errcode = 'P0001', hint = 'COUPON_INVALID';
    end if;
    if v_subtotal < v_coupon.min_order_amount then
      raise exception '쿠폰 최소 주문 금액(%원)에 못 미칩니다', v_coupon.min_order_amount
        using errcode = 'P0001', hint = 'COUPON_MIN_AMOUNT';
    end if;
    v_discount := private.coupon_discount(v_coupon, v_subtotal);
  end if;

  insert into public.orders (
    user_id, status, total_amount, discount_amount, payment_method, items,
    shipping_address, recipient_name, recipient_phone
  ) values (
    v_user_id, '결제대기', v_subtotal + v_shipping_fee - v_discount, v_discount, p_payment_method, v_order_items,
    p_shipping_address, p_recipient_name, p_recipient_phone
  )
  returning * into v_order;

  -- 상품 줄 저장 (같은 트랜잭션: 하나라도 실패하면 주문·재고 차감까지 모두 취소)
  insert into public.order_items (
    order_id, product_id, variant_id, brand, product_name, option_text, sku, image_url, unit_price, quantity
  )
  select v_order.id, (i ->> 'product_id')::bigint, (i ->> 'variant_id')::bigint, i ->> 'brand', i ->> 'name',
         i ->> 'option_text', i ->> 'sku', nullif(i ->> 'image', ''), (i ->> 'price')::integer, (i ->> 'quantity')::integer
    from jsonb_array_elements(v_order_items) as i;

  -- 쿠폰 사용 처리 (같은 트랜잭션: 주문이 실패하면 사용 처리도 취소된다)
  if p_user_coupon_id is not null then
    update public.user_coupons
       set used_at = now(), order_id = v_order.id
     where id = p_user_coupon_id and used_at is null;
  end if;

  return v_order;
end;
$$;

create or replace function public.place_order(
  p_items             jsonb,
  p_shipping_address  text,
  p_recipient_name    text,
  p_recipient_phone   text,
  p_payment_method    text default '카드',
  p_user_coupon_id    bigint default null
)
returns public.orders
language sql volatile security invoker set search_path = ''
as $$
  select * from private.place_order_impl(
    p_items, p_shipping_address, p_recipient_name, p_recipient_phone, p_payment_method, p_user_coupon_id
  );
$$;


-- ---------------------------------------------------------------------
-- 5. 쿠폰 복구: 주문이 결제실패·결제취소·주문취소가 되면 그 주문에 쓴 쿠폰을 다시 사용 가능하게
--    (반품완료는 복구하지 않는다: 상품을 받은 뒤의 반품은 쿠폰을 소진한 것으로 본다)
-- ---------------------------------------------------------------------
create or replace function private.restore_coupon_on_cancel()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.status in ('주문취소', '결제실패', '결제취소')
     and old.status not in ('주문취소', '결제실패', '결제취소') then
    update public.user_coupons
       set used_at = null, order_id = null
     where order_id = new.id;
  end if;
  return new;
end;
$$;

create trigger orders_restore_coupon_on_cancel
  after update of status on public.orders
  for each row execute function private.restore_coupon_on_cancel();


-- ---------------------------------------------------------------------
-- 6. 발급: 가입 시 자동 발급 쿠폰 (public.users에 회원 행이 생길 때)
-- ---------------------------------------------------------------------
create or replace function private.issue_signup_coupons()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.user_coupons (user_id, coupon_id, expires_at)
  select new.id, c.id, now() + make_interval(days => c.valid_days)
    from public.coupons c
   where c.issue_on_signup and c.is_active
  on conflict (user_id, coupon_id) do nothing;
  return new;
end;
$$;

create trigger users_issue_signup_coupons
  after insert on public.users
  for each row execute function private.issue_signup_coupons();


-- ---------------------------------------------------------------------
-- 7. 실행 권한
-- ---------------------------------------------------------------------
revoke execute on function private.place_order_impl(jsonb, text, text, text, text, bigint) from public, anon;
grant  execute on function private.place_order_impl(jsonb, text, text, text, text, bigint) to authenticated;
revoke execute on function public.place_order(jsonb, text, text, text, text, bigint) from public, anon;
grant  execute on function public.place_order(jsonb, text, text, text, text, bigint) to authenticated;

revoke execute on function private.coupon_discount(public.coupons, integer) from public, anon, authenticated;
revoke execute on function private.guard_order_discount()      from public, anon, authenticated;
revoke execute on function private.restore_coupon_on_cancel()  from public, anon, authenticated;
revoke execute on function private.issue_signup_coupons()      from public, anon, authenticated;


