-- =====================================================================
-- 0005 결제 승인 검증
-- =====================================================================
-- 해결하는 문제
--   P1-b  결제 성공 페이지가 주소창의 paymentKey·amount를 결제사에 확인하지 않고 '결제완료' 주문을 만든다.
--         가짜 paymentKey로도 결제완료 주문이 생긴다.
--
-- 바뀌는 결제 흐름
--   ① 주문서: place_order() → '결제대기' 주문 생성 (재고 확보, 서버가 금액 계산)
--   ② 그 주문 id·서버 금액으로 Toss 결제창 호출
--   ③ 성공 페이지 → Edge Function(confirm-payment)이 Toss 승인 API 호출
--        - 주문 소유자·상태·금액을 DB와 대조, Toss 응답 금액도 다시 대조
--        - 승인되면 complete_order_payment()로 '결제완료' + payments 기록 (한 트랜잭션)
--        - 거절되면 '결제실패'로 바꾸고 트리거가 재고 복구
--   ④ 결제를 취소하고 돌아오면 cancel_pending_order()로 '결제취소' + 재고 복구
--
-- 결제 승인 결과를 기록하는 쓰기 작업은 Toss 시크릿 키를 가진 Edge Function(service_role)만 할 수 있다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. 결제 기록 테이블 (주문과 분리: 부분 취소·재결제 이력을 쌓을 수 있도록)
-- ---------------------------------------------------------------------
create table public.payments (
  id           bigint generated by default as identity primary key,
  order_id     text not null references public.orders (id) on delete restrict,
  payment_key  text not null unique,      -- 같은 결제를 두 번 승인 처리하지 않도록(멱등성)
  method       text,
  amount       integer not null check (amount >= 0),
  status       text not null,             -- Toss 응답 status (DONE 등)
  approved_at  timestamptz,
  raw          jsonb not null,            -- Toss 응답 원본 (분쟁·디버깅용)
  created_at   timestamptz not null default now()
);

create index payments_order_id_idx on public.payments (order_id);

alter table public.payments enable row level security;

create policy "payments: 고객 본인 주문의 결제 조회" on public.payments
  for select to authenticated
  using (exists (select 1 from public.orders o where o.id = payments.order_id and o.user_id = (select auth.uid())));
create policy "payments: 본사 조회" on public.payments
  for select to authenticated using ((select private.is_hq()));
-- 쓰기 정책 없음: service_role(Edge Function)만 기록한다


-- ---------------------------------------------------------------------
-- 2. place_order: '결제대기'로 생성 (결제 키는 승인 단계에서만 기록)
--    시그니처에서 p_payment_key를 제거한다. 결제 전에 만드는 주문이므로 받을 결제 키가 없다.
-- ---------------------------------------------------------------------
drop function public.place_order(jsonb, text, text, text, text, text);

create or replace function private.place_order_impl(
  p_items             jsonb,
  p_shipping_address  text,
  p_recipient_name    text,
  p_recipient_phone   text,
  p_payment_method    text
)
returns public.orders
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id      uuid := auth.uid();
  v_item         jsonb;
  v_quantity     integer;
  v_product      public.products;
  v_order_items  jsonb := '[]'::jsonb;
  v_subtotal     integer := 0;
  v_shipping_fee integer;
  v_grade        text;
  v_order        public.orders;
begin
  if v_user_id is null then
    raise exception '로그인이 필요합니다' using errcode = '28000';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception '주문할 상품이 없습니다' using errcode = '22023';
  end if;

  for v_item in
    select value from jsonb_array_elements(p_items) order by (value ->> 'product_id')::bigint
  loop
    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity is null or v_quantity <= 0 or v_quantity > 99 then
      raise exception '주문 수량이 올바르지 않습니다' using errcode = '22023';
    end if;

    update public.products p
       set stock      = p.stock - v_quantity,
           sales      = p.sales + v_quantity,
           status     = case when p.stock - v_quantity = 0 then 'soldout' else p.status end,
           updated_at = now()
     where p.id = (v_item ->> 'product_id')::bigint
       and p.status = 'forsale'
       and p.stock >= v_quantity
    returning p.* into v_product;

    if not found then
      select * into v_product from public.products p where p.id = (v_item ->> 'product_id')::bigint;
      if v_product.id is null then
        raise exception '존재하지 않는 상품입니다 (id=%)', v_item ->> 'product_id' using errcode = 'P0002';
      end if;
      raise exception '재고가 부족합니다: % (남은 수량 %개)', v_product.name, v_product.stock
        using errcode = 'P0001', hint = 'OUT_OF_STOCK';
    end if;

    v_order_items := v_order_items || jsonb_build_object(
      'product_id', v_product.id,
      'name',       v_product.name,
      'brand',      v_product.brand,
      'price',      v_product.price,
      'quantity',   v_quantity,
      'size',       v_item ->> 'size',
      'color',      v_item ->> 'color',
      'image',      coalesce(v_product.image_urls[1], '')
    );
    v_subtotal := v_subtotal + v_product.price * v_quantity;
  end loop;

  select u.grade into v_grade from public.users u where u.id = v_user_id;
  v_shipping_fee := case when v_grade in ('SILVER', 'GOLD', 'DIAMOND', 'PRESTIGE VIP') then 0 else 3000 end;

  insert into public.orders (
    user_id, status, total_amount, payment_method, items,
    shipping_address, recipient_name, recipient_phone
  ) values (
    v_user_id, '결제대기', v_subtotal + v_shipping_fee, p_payment_method, v_order_items,
    p_shipping_address, p_recipient_name, p_recipient_phone
  )
  returning * into v_order;

  return v_order;
end;
$$;

drop function private.place_order_impl(jsonb, text, text, text, text, text);

create or replace function public.place_order(
  p_items             jsonb,
  p_shipping_address  text,
  p_recipient_name    text,
  p_recipient_phone   text,
  p_payment_method    text default '카드'
)
returns public.orders
language sql volatile security invoker set search_path = ''
as $$
  select * from private.place_order_impl(p_items, p_shipping_address, p_recipient_name, p_recipient_phone, p_payment_method);
$$;

revoke execute on function private.place_order_impl(jsonb, text, text, text, text) from public, anon;
grant execute on function private.place_order_impl(jsonb, text, text, text, text) to authenticated;
revoke execute on function public.place_order(jsonb, text, text, text, text) from public, anon;
grant execute on function public.place_order(jsonb, text, text, text, text) to authenticated;


-- ---------------------------------------------------------------------
-- 3. 결제 승인 완료 처리 (Edge Function 전용, service_role만 실행 가능)
--    Edge Function이 Toss 승인 응답을 받은 뒤 호출한다. 주문 상태 변경과 결제 기록을 한 트랜잭션으로.
-- ---------------------------------------------------------------------
create or replace function public.complete_order_payment(
  p_order_id     text,
  p_payment_key  text,
  p_amount       integer,
  p_method       text,
  p_status       text,
  p_approved_at  timestamptz,
  p_raw          jsonb
)
returns public.orders
language plpgsql security definer set search_path = ''
as $$
declare
  v_order public.orders;
begin
  -- 같은 결제 키가 이미 처리되었으면 기존 주문을 그대로 돌려준다 (새로고침·중복 요청에도 한 번만 처리)
  if exists (select 1 from public.payments where payment_key = p_payment_key) then
    select o.* into v_order from public.orders o join public.payments p on p.order_id = o.id
     where p.payment_key = p_payment_key;
    return v_order;
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if v_order.id is null then
    raise exception '주문을 찾을 수 없습니다' using errcode = 'P0002';
  end if;
  if v_order.status <> '결제대기' then
    raise exception '결제 대기 상태의 주문이 아닙니다 (현재: %)', v_order.status using errcode = '22023';
  end if;
  if v_order.total_amount <> p_amount then
    raise exception '결제 금액이 주문 금액과 다릅니다 (주문 %원, 결제 %원)', v_order.total_amount, p_amount
      using errcode = '22023', hint = 'AMOUNT_MISMATCH';
  end if;

  insert into public.payments (order_id, payment_key, method, amount, status, approved_at, raw)
  values (p_order_id, p_payment_key, p_method, p_amount, p_status, p_approved_at, p_raw);

  update public.orders
     set status = '결제완료', payment_key = p_payment_key,
         payment_method = coalesce(p_method, payment_method), updated_at = now()
   where id = p_order_id
  returning * into v_order;

  return v_order;
end;
$$;

-- 결제 실패 처리 (Edge Function 전용): '결제실패'로 바꾸면 트리거가 재고를 복구한다
create or replace function public.fail_order_payment(p_order_id text, p_reason text)
returns void
language sql security definer set search_path = ''
as $$
  update public.orders
     set status = '결제실패', cancel_reason = left(p_reason, 500), updated_at = now()
   where id = p_order_id and status = '결제대기';
$$;

revoke execute on function public.complete_order_payment(text, text, integer, text, text, timestamptz, jsonb) from public, anon, authenticated;
grant execute on function public.complete_order_payment(text, text, integer, text, text, timestamptz, jsonb) to service_role;
revoke execute on function public.fail_order_payment(text, text) from public, anon, authenticated;
grant execute on function public.fail_order_payment(text, text) to service_role;


-- ---------------------------------------------------------------------
-- 4. 고객이 결제창에서 취소하고 돌아왔을 때: 본인의 '결제대기' 주문만 '결제취소'로
-- ---------------------------------------------------------------------
create or replace function private.cancel_pending_order_impl(p_order_id text)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  update public.orders
     set status = '결제취소', updated_at = now()
   where id = p_order_id and user_id = auth.uid() and status = '결제대기';
end;
$$;

create or replace function public.cancel_pending_order(p_order_id text)
returns void
language sql volatile security invoker set search_path = ''
as $$
  select private.cancel_pending_order_impl(p_order_id);
$$;

revoke execute on function private.cancel_pending_order_impl(text) from public, anon;
grant execute on function private.cancel_pending_order_impl(text) to authenticated;
revoke execute on function public.cancel_pending_order(text) from public, anon;
grant execute on function public.cancel_pending_order(text) to authenticated;


-- ---------------------------------------------------------------------
-- 5. 재고 복구 트리거: 주문취소뿐 아니라 결제실패·결제취소에도 복구
-- ---------------------------------------------------------------------
create or replace function private.restore_stock_on_cancel()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_item jsonb;
begin
  if new.status in ('주문취소', '결제실패', '결제취소')
     and old.status not in ('주문취소', '결제실패', '결제취소') then
    for v_item in select value from jsonb_array_elements(coalesce(old.items, '[]'::jsonb)) order by (value ->> 'product_id')::bigint
    loop
      update public.products p
         set stock      = p.stock + (v_item ->> 'quantity')::integer,
             sales      = greatest(0, p.sales - (v_item ->> 'quantity')::integer),
             status     = case when p.status = 'soldout' then 'forsale' else p.status end,
             updated_at = now()
       where p.id = (v_item ->> 'product_id')::bigint;
    end loop;
  end if;
  return new;
end;
$$;


-- ---------------------------------------------------------------------
-- 6. 주문 수정 규칙: 결제 상태 전환은 서버 함수만 할 수 있다
--    - service_role(Edge Function)·DB 직접 접속(관리 작업)은 규칙 적용 제외
--    - 고객은 '취소요청'·'반품신청'만, 결제대기 주문의 상태를 직접 바꿀 수 없다
-- ---------------------------------------------------------------------
create or replace function private.guard_orders_update()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_jwt_role text := coalesce(auth.jwt() ->> 'role', '');
begin
  if v_jwt_role = 'service_role' or (v_jwt_role = '' and auth.uid() is null) or private.is_hq() then
    return new;
  end if;
  -- 결제 상태 전환('결제대기' -> 결제완료/결제실패/결제취소)은 위의 서버 함수가 처리한다
  -- (cancel_pending_order_impl은 definer지만 auth.uid()가 고객이므로 아래 예외로 허용)
  if old.status = '결제대기' and new.status = '결제취소' and old.user_id = auth.uid()
     and (new.user_id, new.total_amount, new.items, new.payment_key) is not distinct from
         (old.user_id, old.total_amount, old.items, old.payment_key) then
    return new;
  end if;
  if (new.user_id, new.total_amount, new.items, new.payment_key, new.payment_method, new.order_date)
     is distinct from
     (old.user_id, old.total_amount, old.items, old.payment_key, old.payment_method, old.order_date) then
    raise exception '주문 금액·상품·결제 정보는 변경할 수 없습니다' using errcode = '42501';
  end if;
  if old.status in ('결제대기', '결제실패', '결제취소') and new.status is distinct from old.status then
    raise exception '결제 상태는 결제 승인 과정에서만 바뀝니다' using errcode = '42501';
  end if;
  if private.my_brand_name() is null
     and new.status is distinct from old.status
     and new.status not in ('취소요청', '반품신청') then
    raise exception '고객은 취소 요청 또는 반품 신청만 할 수 있습니다' using errcode = '42501';
  end if;
  return new;
end;
$$;
