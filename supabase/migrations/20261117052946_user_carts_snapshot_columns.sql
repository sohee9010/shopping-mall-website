-- =====================================================================
-- 0006 baseline 복원 누락 보완: 장바구니 상품 정보 컬럼
-- =====================================================================
-- 증상: 로그인 회원이 상품을 장바구니에 담아도 장바구니가 비어 있다.
-- 원인: 앱(src/services/cartService.ts cartItemToDbItem)은 장바구니에 상품명·가격·이미지·브랜드를 함께 저장하는데,
--       baseline 복원 때 이 컬럼들을 만들지 않았다. 저장 요청이 '없는 컬럼' 오류로 거부되고, 앱은 오류를 콘솔에만 남겼다.
-- 누락 이유: 역분석 스크립트가 insert/upsert에 '직접 쓴 객체'만 분석했고, 이 코드는 별도 함수로 만든 객체를
--           스프레드(...dbItem)로 넘겨 잡히지 않았다. 정상 기능 테스트도 앱과 다른 최소 데이터로 장바구니를 담아 놓쳤다.
--           → 재현 스크립트의 장바구니 테스트를 앱과 같은 데이터 형태로 바꿔 재발을 막는다.
--
-- 참고: 이 값들은 '담을 때의 표시용 사본'이다. 실제 결제 금액은 place_order가 DB의 현재 가격으로 다시 계산하므로
--       장바구니에 오래된 가격이 남아 있어도 결제 금액에는 영향이 없다.
-- =====================================================================

alter table public.user_carts
  add column product_name  text,
  add column product_price integer,
  add column product_image text,
  add column brand         text;
